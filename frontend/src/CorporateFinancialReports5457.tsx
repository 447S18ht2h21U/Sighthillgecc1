import React, { useEffect, useState } from 'react';

type FinancialReport = {
  id: string;
  kind: string;
  period_start: string;
  period_end: string;
  status: string;
  approved_at: string | null;
  report_snapshot: unknown;
};

type ReportResponse = { results: FinancialReport[] };

const titles: Record<string, string> = {
  INCOME_STATEMENT: 'Income Statement',
  BALANCE_SHEET: 'Balance Sheet',
  CASH_FLOW: 'Cash Flow Statement',
  PROJECT_PROFITABILITY: 'Project Profitability',
};

export function CorporateFinancialReports5457({
  api,
}: {
  api: (path: string) => Promise<ReportResponse>;
}): React.JSX.Element {
  const [reports, setReports] = useState<FinancialReport[]>([]);
  const [selectedId, setSelectedId] = useState<string | null>(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');

  useEffect(() => {
    let active = true;

    api('financial-reports/')
      .then(data => {
        if (!active) return;
        setReports(data.results);
        setSelectedId(data.results[0]?.id ?? null);
      })
      .catch(reason => {
        if (active) {
          setError(reason instanceof Error
            ? reason.message : 'Unable to load reports.');
        }
      })
      .finally(() => {
        if (active) setLoading(false);
      });

    return () => { active = false; };
  }, [api]);

  const selected = reports.find(item => item.id === selectedId);

  return (
    <section
      aria-label="Corporate Financial Reports"
      style={{
        marginTop: 16,
        padding: 20,
        background: '#F7F8F5',
        border: '1px solid #D7E3E7',
        borderRadius: 8,
      }}
    >
      <h2>Corporate Financial Reports</h2>
      <p>
        Saved reports from VERIDIAN. Read-only: no report creation,
        approval, payment recording, or exports are enabled here.
      </p>

      {loading && <p role="status">Loading saved reports...</p>}
      {error && <p role="alert">{error}</p>}

      {!loading && !error && reports.length === 0 && (
        <p role="status">
          No saved corporate financial reports are available.
          No statement amounts have been generated by this screen.
        </p>
      )}

      {!loading && !error && reports.length > 0 && (
        <>
          <p>{reports.length} saved report(s) available.</p>
          <div style={{ overflowX: 'auto' }}>
            <table style={{ width: '100%', textAlign: 'left' }}>
              <thead>
                <tr>
                  <th scope="col">Statement</th>
                  <th scope="col">Period</th>
                  <th scope="col">Status</th>
                  <th scope="col">Review</th>
                </tr>
              </thead>
              <tbody>
                {reports.map(item => (
                  <tr key={item.id}>
                    <td>{titles[item.kind] ?? item.kind}</td>
                    <td>{item.period_start} to {item.period_end}</td>
                    <td>{item.status}</td>
                    <td>
                      <button
                        type="button"
                        aria-pressed={selectedId === item.id}
                        onClick={() => setSelectedId(item.id)}
                      >
                        View statement
                      </button>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {selected && (
            <section
              aria-label="Selected financial statement"
              style={{
                marginTop: 20,
                padding: 16,
                background: 'white',
                border: '1px solid #D7E3E7',
                borderRadius: 8,
              }}
            >
              <h3>{titles[selected.kind] ?? selected.kind}</h3>
              <p>
                Period: {selected.period_start} to {selected.period_end}
              </p>
              <p>Status: <strong>{selected.status}</strong></p>
              <p>
                Approval recorded: {selected.approved_at ?? 'No'}
              </p>
              <h4>Saved statement data</h4>
              <pre style={{
                whiteSpace: 'pre-wrap',
                overflowWrap: 'anywhere',
                background: '#F7F8F5',
                padding: 12,
                fontSize: 13,
              }}>
                {JSON.stringify(selected.report_snapshot, null, 2)}
              </pre>
            </section>
          )}
        </>
      )}
    </section>
  );
}